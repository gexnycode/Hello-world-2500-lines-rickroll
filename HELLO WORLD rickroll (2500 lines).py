def ram_to_bytes():
    """Turn the binary RAM rows into a flat bytes object."""
    out = bytearray()
    for _address, bits in RAM_DUMP:
        for i in range(0, len(bits), 8):
            out.append(int(bits[i:i + 8], 2))
    return bytes(out)


def read_string(ram, address):
    """Read bytes from RAM starting at address until a 0x00 terminator."""
    chars = []
    while address < len(ram) and ram[address] != 0:
        chars.append(chr(ram[address]))
        address += 1
    return "".join(chars)


def show_ram_rows(first, last):
    """Pretty-print some RAM rows."""
    for row in range(first, last + 1):
        address, bits = RAM_DUMP[row]
        print("0x%04X  %s" % (address, bits))


